/* "type [COLLATE c] [NOT NULL|NULL] [DEFAULT x] [AUTO_INCREMENT] [COMMENT 'x']" for MySQL,
 * "type [COLLATE c] [NOT NULL] [DEFAULT x] [GENERATED ...]" for PostgreSQL, SQLite's subset */
static char *column_def(LaceDriver d, const LaceDdlColumn *c, const char *type, bool with_name) {
  StringBuilder *sb = sb_new(128);
  if (with_name) {
    char *q = ident(d, c->name);
    sb_printf(sb, "%s ", q);
    free(q);
  }
  sb_append(sb, type);
  if (!blank(c->collation)) {
    char *cs = collation_sql(d, c->collation);
    sb_printf(sb, " COLLATE %s", cs);
    free(cs);
  }
  if (!c->nullable) sb_append(sb, " NOT NULL");
  else if (is_mysql(d)) sb_append(sb, " NULL");
  if (!blank(c->default_sql)) sb_printf(sb, " DEFAULT %s", c->default_sql);
  if (c->auto_increment) {
    if (is_mysql(d)) sb_append(sb, " AUTO_INCREMENT");
    else if (d == LACE_DRIVER_POSTGRES) sb_append(sb, " GENERATED BY DEFAULT AS IDENTITY");
  }
  if (is_mysql(d) && c->comment) {
    char *l = lit(d, c->comment);
    sb_printf(sb, " COMMENT %s", l);
    free(l);
  }
  return sb_finish(sb);
}

char *lace_ddl_add_column(LaceDriver d, const char *table, const LaceDdlColumn *c, char **error) {
  if (error) *error = NULL;
  if (blank(table) || !c || blank(c->name) || blank(c->type)) return refuse(error, "A column needs a name and a type");
  if (d == LACE_DRIVER_SQLITE) {
    if (c->auto_increment) return refuse(error, "SQLite cannot add an auto-increment column (ADD COLUMN takes no PRIMARY KEY); " SQLITE_CANNOT);
    if (!c->nullable && blank(c->default_sql))
      return refuse(error, "SQLite needs a default for a NOT NULL column added to a table");
    if (!blank(c->default_sql) && strncasecmp(c->default_sql, "CURRENT_", 8) == 0)
      return refuse(error, "SQLite refuses CURRENT_TIME, CURRENT_DATE and CURRENT_TIMESTAMP as the default of an added column");
  }
  char *t = tbl(d, table), *def = column_def(d, c, c->type, true);
  StringBuilder *sb = sb_new(128);
  sb_printf(sb, "ALTER TABLE %s ADD COLUMN %s", t, def);
  if (is_mysql(d) && c->after) {
    if (*c->after) {
      char *a = ident(d, c->after);
      sb_printf(sb, " AFTER %s", a);
      free(a);
    } else {
      sb_append(sb, " FIRST");
    }
  }
  if (d == LACE_DRIVER_POSTGRES && c->comment && *c->comment) {
    char *col = ident(d, c->name), *l = lit(d, c->comment);
    sb_printf(sb, ";\nCOMMENT ON COLUMN %s.%s IS %s", t, col, l);
    free(col);
    free(l);
  }
  free(t);
  free(def);
  return sb_finish(sb);
}

char *lace_ddl_drop_column(LaceDriver d, const char *table, const char *column, char **error) {
  if (error) *error = NULL;
  if (blank(table) || blank(column)) return refuse(error, "A table and a column are needed");
  char *t = tbl(d, table), *c = ident(d, column);
  char *sql = str_printf("ALTER TABLE %s DROP COLUMN %s", t, c);
  free(t);
  free(c);
  return sql;
}

char *lace_ddl_rename_column(LaceDriver d, const char *table, const char *column, const char *new_name, char **error) {
  if (error) *error = NULL;
  if (blank(table) || blank(column) || blank(new_name)) return refuse(error, "A table, a column and a new name are needed");
  char *t = tbl(d, table), *c = ident(d, column), *n = ident(d, new_name);
  char *sql = str_printf("ALTER TABLE %s RENAME COLUMN %s TO %s", t, c, n);
  free(t);
  free(c);
  free(n);
  return sql;
}

static bool same_text(const char *a, const char *b) {
  if (blank(a) && blank(b)) return true;
  if (blank(a) || blank(b)) return false;
  return strcmp(a, b) == 0;
}

char *lace_ddl_alter_column(LaceDriver d, const char *table, const LaceColumn *cur, const LaceDdlColumn *w,
                            char **error) {
  if (error) *error = NULL;
  if (blank(table) || !cur || !w || blank(cur->name)) return refuse(error, "A table and a column are needed");
  const char *type = blank(w->type) ? cur->type_name : w->type;
  bool type_changed = !same_text(type, cur->type_name);
  bool collation_changed = !same_text(w->collation, cur->collation);
  bool default_changed = !same_text(w->default_sql, cur->default_val);
  bool nullable_changed = w->nullable != cur->nullable;
  bool comment_changed = w->comment && !same_text(w->comment, cur->comment);
  bool cur_ai = cur->auto_increment || cur->identity != 0;
  bool ai_changed = w->auto_increment != cur_ai;
  if (!type_changed && !collation_changed && !default_changed && !nullable_changed && !comment_changed && !ai_changed &&
      !(is_mysql(d) && w->after))
    return refuse(error, "No change");
  if (d == LACE_DRIVER_SQLITE) return refuse(error, SQLITE_CANNOT);
  if (cur->generated) return refuse(error, "A generated column is not altered here; drop it and add it again");
  char *t = tbl(d, table), *c = ident(d, cur->name);
  StringBuilder *sb = sb_new(256);
  if (is_mysql(d)) {
    LaceDdlColumn full = *w;
    if (!full.comment) full.comment = cur->comment;
    char *def = column_def(d, &full, type ? type : "", true);
    sb_printf(sb, "ALTER TABLE %s MODIFY COLUMN %s", t, def);
    free(def);
    if (w->after) {
      if (*w->after) {
        char *a = ident(d, w->after);
        sb_printf(sb, " AFTER %s", a);
        free(a);
      } else {
        sb_append(sb, " FIRST");
      }
    }
  } else { /* PostgreSQL: one ALTER TABLE, an action per difference */
    bool any = false;
    sb_printf(sb, "ALTER TABLE %s", t);
    if (type_changed || collation_changed) {
      sb_printf(sb, "%s ALTER COLUMN %s TYPE %s", any ? "," : "", c, type ? type : "");
      if (!blank(w->collation)) {
        char *cs = collation_sql(d, w->collation);
        sb_printf(sb, " COLLATE %s", cs);
        free(cs);
      }
      any = true;
    }
    if (default_changed) {
      if (blank(w->default_sql)) sb_printf(sb, "%s ALTER COLUMN %s DROP DEFAULT", any ? "," : "", c);
      else sb_printf(sb, "%s ALTER COLUMN %s SET DEFAULT %s", any ? "," : "", c, w->default_sql);
      any = true;
    }
    if (nullable_changed) {
      sb_printf(sb, "%s ALTER COLUMN %s %s NOT NULL", any ? "," : "", c, w->nullable ? "DROP" : "SET");
      any = true;
    }
    if (ai_changed) {
      if (w->auto_increment) sb_printf(sb, "%s ALTER COLUMN %s ADD GENERATED BY DEFAULT AS IDENTITY", any ? "," : "", c);
      else sb_printf(sb, "%s ALTER COLUMN %s DROP IDENTITY IF EXISTS", any ? "," : "", c);
      any = true;
    }
    if (!any) { /* only the comment */
      sb_free(sb);
      sb = sb_new(128);
    }
    if (comment_changed) {
      char *l = blank(w->comment) ? str_dup("NULL") : lit(d, w->comment);
      sb_printf(sb, "%sCOMMENT ON COLUMN %s.%s IS %s", any ? ";\n" : "", t, c, l);
      free(l);
    }
  }
  free(t);
  free(c);
  return sb_finish(sb);
}

char *lace_ddl_set_primary_key(LaceDriver d, const char *table, const char *const *columns, size_t n,
                               const char *existing, char **error) {
  if (error) *error = NULL;
  if (blank(table)) return refuse(error, "A table is needed");
  if (d == LACE_DRIVER_SQLITE) return refuse(error, SQLITE_CANNOT);
  char *t = tbl(d, table);
  StringBuilder *sb = sb_new(128);
  sb_printf(sb, "ALTER TABLE %s", t);
  bool any = false;
  if (is_mysql(d) ? !blank(existing) || n == 0 : !blank(existing)) {
    if (is_mysql(d)) {
      sb_append(sb, " DROP PRIMARY KEY");
    } else {
      char *e = ident(d, existing);
      sb_printf(sb, " DROP CONSTRAINT %s", e);
      free(e);
    }
    any = true;
  }
  if (n > 0) {
    char *cols = ident_list(d, columns, n);
    sb_printf(sb, "%s ADD PRIMARY KEY (%s)", any ? "," : "", cols);
    free(cols);
    any = true;
  }
  free(t);
  if (!any) {
    sb_free(sb);
    return refuse(error, "No change");
  }
  return sb_finish(sb);
}

