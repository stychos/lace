char *lace_ddl_view_template(LaceDriver d, const char *name, char **error) {
  if (error) *error = NULL;
  if (blank(name)) return refuse(error, "A view name is needed");
  char *t = tbl(d, name);
  char *sql = str_printf("CREATE VIEW %s AS\nSELECT\n  *\nFROM\n  ", t);
  free(t);
  return sql;
}

char *lace_ddl_routine_template(LaceDriver d, const char *name, char **error) {
  if (error) *error = NULL;
  if (blank(name)) return refuse(error, "A function name is needed");
  if (d == LACE_DRIVER_SQLITE) return refuse(error, "SQLite has no routines");
  char *t = tbl(d, name), *sql;
  if (d == LACE_DRIVER_POSTGRES)
    sql = str_printf("CREATE OR REPLACE FUNCTION %s()\nRETURNS integer\nLANGUAGE sql\nAS $$\n  SELECT 1\n$$", t);
  else
    sql = str_printf("CREATE FUNCTION %s()\nRETURNS INT\nDETERMINISTIC\nRETURN 1", t);
  free(t);
  return sql;
}
