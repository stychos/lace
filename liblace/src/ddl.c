char *lace_ddl_create_index(LaceDriver d, const char *table, const char *name, bool unique, const char *const *columns,
                            size_t n, const char *method, const char *where, char **error) {
  if (error) *error = NULL;
  if (blank(table) || blank(name) || n == 0) return refuse(error, "An index needs a name and at least one column");
  if (!blank(method) && !plain_word(method)) return refuse(error, "The index method must be one word");
  if (!blank(where) && is_mysql(d)) return refuse(error, "MySQL has no partial indexes");
  if (!blank(method) && d == LACE_DRIVER_SQLITE) return refuse(error, "SQLite indexes have no method");
  char *t = tbl(d, table), *nm = ident(d, name), *cols = ident_list(d, columns, n);
  StringBuilder *sb = sb_new(128);
  bool special = is_mysql(d) && method && (strcasecmp(method, "FULLTEXT") == 0 || strcasecmp(method, "SPATIAL") == 0);
  if (special) {
    char *up = str_dup(method);
    for (char *p = up; *p; p++) *p = (char)toupper((unsigned char)*p);
    sb_printf(sb, "CREATE %s INDEX %s ON %s (%s)", up, nm, t, cols);
    free(up);
  } else if (d == LACE_DRIVER_POSTGRES) {
    sb_printf(sb, "CREATE %sINDEX %s ON %s%s%s (%s)", unique ? "UNIQUE " : "", nm, t, blank(method) ? "" : " USING ",
              blank(method) ? "" : method, cols);
    if (!blank(where)) sb_printf(sb, " WHERE %s", where);
  } else if (is_mysql(d)) {
    sb_printf(sb, "CREATE %sINDEX %s ON %s (%s)%s%s", unique ? "UNIQUE " : "", nm, t, cols,
              blank(method) ? "" : " USING ", blank(method) ? "" : method);
  } else {
    sb_printf(sb, "CREATE %sINDEX %s ON %s (%s)", unique ? "UNIQUE " : "", nm, t, cols);
    if (!blank(where)) sb_printf(sb, " WHERE %s", where);
  }
  free(t);
  free(nm);
  free(cols);
  return sb_finish(sb);
}

char *lace_ddl_drop_index(LaceDriver d, const char *table, const char *name, const char *constraint, char **error) {
  if (error) *error = NULL;
  if (blank(name)) return refuse(error, "An index name is needed");
  if (!blank(constraint)) {
    if (d == LACE_DRIVER_SQLITE) return refuse(error, "The index backs a constraint of the table; " SQLITE_CANNOT);
    if (d == LACE_DRIVER_POSTGRES) return lace_ddl_drop_constraint(d, table, constraint, error);
  }
  char *nm = ident(d, name), *sql;
  if (is_mysql(d)) {
    if (blank(table)) {
      free(nm);
      return refuse(error, "MySQL drops an index by its table");
    }
    char *t = tbl(d, table);
    sql = str_printf("DROP INDEX %s ON %s", nm, t);
    free(t);
  } else {
    sql = str_printf("DROP INDEX %s", nm);
  }
  free(nm);
  return sql;
}

char *lace_ddl_rename_index(LaceDriver d, const char *table, const LaceIndex *ix, const char *new_name, char **error) {
  if (error) *error = NULL;
  if (!ix || blank(ix->name) || blank(new_name)) return refuse(error, "An index and a new name are needed");
  if (ix->kind == LACE_INDEX_PRIMARY || ix->kind == LACE_INDEX_CHECK || ix->kind == LACE_INDEX_EXCLUSION)
    return refuse(error, "Only an index (or a unique index) is renamed here");
  char *old = ident(d, ix->name), *nm = ident(d, new_name), *sql = NULL;
  if (d == LACE_DRIVER_POSTGRES) {
    if (!blank(ix->constraint)) {
      char *t = tbl(d, table), *c = ident(d, ix->constraint);
      sql = str_printf("ALTER TABLE %s RENAME CONSTRAINT %s TO %s", t, c, nm);
      free(t);
      free(c);
    } else {
      sql = str_printf("ALTER INDEX %s RENAME TO %s", old, nm);
    }
  } else if (d == LACE_DRIVER_MYSQL) {
    char *t = tbl(d, table);
    sql = str_printf("ALTER TABLE %s RENAME INDEX %s TO %s", t, old, nm);
    free(t);
  } else { /* SQLite, MariaDB: drop and create from what was read */
    if (!blank(ix->constraint) && d == LACE_DRIVER_SQLITE) {
      free(old);
      free(nm);
      return refuse(error, "The index backs a constraint of the table; " SQLITE_CANNOT);
    }
    for (size_t k = 0; k < ix->num_columns; k++)
      if (!plain_word(ix->columns[k])) {
        free(old);
        free(nm);
        return refuse(error, "An index on an expression is not recreated here; drop it and create it again");
      }
    char *drop = lace_ddl_drop_index(d, table, ix->name, NULL, error);
    char *create = drop ? lace_ddl_create_index(d, table, new_name, ix->unique, (const char *const *)ix->columns,
                                                ix->num_columns, d == LACE_DRIVER_SQLITE ? NULL : ix->type, ix->where,
                                                error)
                        : NULL;
    if (drop && create) sql = str_printf("%s;\n%s", drop, create);
    free(drop);
    free(create);
  }
  free(old);
  free(nm);
  return sql;
}

char *lace_ddl_add_check(LaceDriver d, const char *table, const char *name, const char *condition, char **error) {
  if (error) *error = NULL;
  if (blank(table) || blank(condition)) return refuse(error, "A table and a condition are needed");
  if (d == LACE_DRIVER_SQLITE) return refuse(error, "SQLite takes check constraints only when the table is created; " SQLITE_CANNOT);
  char *t = tbl(d, table);
  char *sql;
  if (blank(name)) {
    sql = str_printf("ALTER TABLE %s ADD CHECK (%s)", t, condition);
  } else {
    char *nm = ident(d, name);
    sql = str_printf("ALTER TABLE %s ADD CONSTRAINT %s CHECK (%s)", t, nm, condition);
    free(nm);
  }
  free(t);
  return sql;
}

char *lace_ddl_drop_constraint(LaceDriver d, const char *table, const char *name, char **error) {
  if (error) *error = NULL;
  if (blank(table) || blank(name)) return refuse(error, "A table and a constraint are needed");
  if (d == LACE_DRIVER_SQLITE) return refuse(error, SQLITE_CANNOT);
  char *t = tbl(d, table), *nm = ident(d, name);
  char *sql = str_printf("ALTER TABLE %s DROP CONSTRAINT %s", t, nm);
  free(t);
  free(nm);
  return sql;
}

char *lace_ddl_add_foreign_key(LaceDriver d, const char *table, const LaceDdlForeignKey *fk, char **error) {
  if (error) *error = NULL;
  if (blank(table) || !fk || fk->num_columns == 0 || blank(fk->ref_table) || fk->num_ref_columns != fk->num_columns)
    return refuse(error, "A foreign key needs columns and as many referenced columns");
  if (d == LACE_DRIVER_SQLITE) return refuse(error, "SQLite cannot add a foreign key to an existing table; " SQLITE_CANNOT);
  if (!blank(fk->on_delete) && !valid_action(fk->on_delete)) return refusef(error, "Unknown ON DELETE action: %s", fk->on_delete);
  if (!blank(fk->on_update) && !valid_action(fk->on_update)) return refusef(error, "Unknown ON UPDATE action: %s", fk->on_update);
  if ((fk->deferrable || fk->initially_deferred) && d != LACE_DRIVER_POSTGRES)
    return refuse(error, "Only PostgreSQL has deferrable constraints");
  char *t = tbl(d, table), *cols = ident_list(d, fk->columns, fk->num_columns);
  char *rt = tbl(d, fk->ref_table), *rcols = ident_list(d, fk->ref_columns, fk->num_ref_columns);
  StringBuilder *sb = sb_new(256);
  sb_printf(sb, "ALTER TABLE %s ADD", t);
  if (!blank(fk->name)) {
    char *nm = ident(d, fk->name);
    sb_printf(sb, " CONSTRAINT %s", nm);
    free(nm);
  }
  sb_printf(sb, " FOREIGN KEY (%s) REFERENCES %s (%s)", cols, rt, rcols);
  if (!blank(fk->on_delete)) sb_printf(sb, " ON DELETE %s", fk->on_delete);
  if (!blank(fk->on_update)) sb_printf(sb, " ON UPDATE %s", fk->on_update);
  if (fk->deferrable || fk->initially_deferred)
    sb_printf(sb, " DEFERRABLE%s", fk->initially_deferred ? " INITIALLY DEFERRED" : "");
  free(t);
  free(cols);
  free(rt);
  free(rcols);
  return sb_finish(sb);
}

char *lace_ddl_drop_foreign_key(LaceDriver d, const char *table, const char *name, char **error) {
  if (error) *error = NULL;
  if (blank(table) || blank(name)) return refuse(error, "A table and a constraint are needed");
  if (d == LACE_DRIVER_SQLITE) return refuse(error, "SQLite cannot drop a foreign key; " SQLITE_CANNOT);
  if (!is_mysql(d)) return lace_ddl_drop_constraint(d, table, name, error);
  char *t = tbl(d, table), *nm = ident(d, name);
  char *sql = str_printf("ALTER TABLE %s DROP FOREIGN KEY %s", t, nm);
  free(t);
  free(nm);
  return sql;
}

