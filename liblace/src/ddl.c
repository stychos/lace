char *lace_ddl_truncate(LaceDriver d, const char *table, char **error) {
  if (error) *error = NULL;
  if (blank(table)) return refuse(error, "A table is needed");
  char *t = tbl(d, table);
  char *sql = d == LACE_DRIVER_SQLITE ? str_printf("DELETE FROM %s", t) : str_printf("TRUNCATE TABLE %s", t);
  free(t);
  return sql;
}

char *lace_ddl_drop_table(LaceDriver d, const char *table, bool cascade, char **error) {
  if (error) *error = NULL;
  if (blank(table)) return refuse(error, "A table is needed");
  if (cascade && d != LACE_DRIVER_POSTGRES) return refuse(error, "Only PostgreSQL drops a table with CASCADE");
  char *t = tbl(d, table);
  char *sql = str_printf("DROP TABLE %s%s", t, cascade ? " CASCADE" : "");
  free(t);
  return sql;
}

char *lace_ddl_create_table_with_id(LaceDriver d, const char *table, char **error) {
  if (error) *error = NULL;
  if (blank(table)) return refuse(error, "A table name is needed");
  char *t = tbl(d, table);
  const char *id;
  switch (d) {
  case LACE_DRIVER_SQLITE: id = "id INTEGER PRIMARY KEY AUTOINCREMENT"; break;
  case LACE_DRIVER_POSTGRES: id = "id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"; break;
  default: id = "id BIGINT AUTO_INCREMENT PRIMARY KEY"; break;
  }
  char *sql = str_printf("CREATE TABLE %s (%s)", t, id);
  free(t);
  return sql;
}

