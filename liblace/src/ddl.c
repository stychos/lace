#define SQLITE_CANNOT "SQLite cannot alter this; create a new table and copy the rows"

static bool is_mysql(LaceDriver d) { return d == LACE_DRIVER_MYSQL || d == LACE_DRIVER_MARIADB; }

/* NULL with the reason */
static char *refuse(char **error, const char *why) {
  if (error) *error = str_dup(why);
  return NULL;
}

static char *refusef(char **error, const char *fmt, const char *a) {
  if (error) *error = str_printf(fmt, a);
  return NULL;
}

static bool blank(const char *s) { return !s || !*s; }

static char *ident(LaceDriver d, const char *name) { return lace_quote_identifier(d, name ? name : ""); }
static char *tbl(LaceDriver d, const char *ref) { return lace_quote_table(d, ref ? ref : ""); }
static char *lit(LaceDriver d, const char *text) { return lace_sql_string_literal(d, text ? text : ""); }

/* "a", "b" */
static char *ident_list(LaceDriver d, const char *const *names, size_t n) {
  StringBuilder *sb = sb_new(64);
  for (size_t i = 0; i < n; i++) {
    char *q = ident(d, names[i]);
    sb_printf(sb, "%s%s", i ? ", " : "", q);
    free(q);
  }
  return sb_finish(sb);
}

/* A plain word needs no quoting; a collation or method name that is not one is quoted */
static bool plain_word(const char *s) {
  if (blank(s)) return false;
  for (const char *c = s; *c; c++)
    if (!isalnum((unsigned char)*c) && *c != '_') return false;
  return true;
}

/* How a collation is spelled after COLLATE: PostgreSQL quotes ("C",
 * "en_US" keep their case), MySQL and SQLite take the word */
static char *collation_sql(LaceDriver d, const char *name) {
  if (d == LACE_DRIVER_POSTGRES || !plain_word(name)) return ident(d, name);
  return str_dup(name);
}

static bool valid_action(const char *a) {
  static const char *const ok[] = {"CASCADE", "SET NULL", "SET DEFAULT", "RESTRICT", "NO ACTION"};
  for (size_t i = 0; i < sizeof ok / sizeof *ok; i++)
    if (strcasecmp(a, ok[i]) == 0) return true;
  return false;
}

