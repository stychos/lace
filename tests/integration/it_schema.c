#include "it.h"
#include <stdlib.h>
#include <string.h>

static const LaceColumn *find_col(const LaceSchema *s, const char *name) {
  for (size_t i = 0; s && i < s->num_columns; i++) {
    if (s->columns[i].name && strcmp(s->columns[i].name, name) == 0)
      return &s->columns[i];
  }
  return NULL;
}

static bool listed(ItDb *db, const char *ref) {
  char **tables = NULL;
  size_t n = 0;
  bool found = false;
  if (lace_list_tables(db->client, db->conn, &tables, &n) == LACE_OK) {
    for (size_t i = 0; i < n; i++)
      found = found || strcmp(tables[i], ref) == 0;
    lace_tables_free(tables, n);
  }
  return found;
}

/* Keys, auto-increment, defaults, NOT NULL and generated columns */
static void test_schema_columns(ItDb *db) {
  it_ex(db, "DROP TABLE IF EXISTS it_cols");
  if (!it_ex(db, "%s",
             it_dialect(db,
                        "CREATE TABLE it_cols (id INTEGER PRIMARY KEY, "
                        "name TEXT NOT NULL DEFAULT 'anon', note TEXT, n INTEGER "
                        "DEFAULT 21, twice INTEGER GENERATED ALWAYS AS (n * 2) VIRTUAL)",
                        "CREATE TABLE it_cols (id INTEGER GENERATED BY DEFAULT AS "
                        "IDENTITY PRIMARY KEY, name TEXT NOT NULL DEFAULT 'anon', "
                        "note TEXT, n INTEGER DEFAULT 21, "
                        "twice INTEGER GENERATED ALWAYS AS (n * 2) STORED)",
                        /* MySQL: a generated column cannot use an
                         * AUTO_INCREMENT one */
                        "CREATE TABLE it_cols (id INT AUTO_INCREMENT PRIMARY KEY, "
                        "name VARCHAR(20) NOT NULL DEFAULT 'anon', note TEXT, "
                        "n INT DEFAULT 21, twice INT GENERATED ALWAYS AS (n * 2) VIRTUAL)")))
    return;
  LaceSchema *s = NULL;
  CHECK_OK(db, lace_get_schema(db->client, db->conn, "it_cols", &s));
  const LaceColumn *id = find_col(s, "id"), *name = find_col(s, "name"),
                   *note = find_col(s, "note"), *twice = find_col(s, "twice");
  CHECK(id && name && note && twice);
  if (id && name && note && twice) {
    CHECK(id->primary_key && id->auto_increment);
    CHECK(!name->primary_key && !name->nullable && name->default_val);
    CHECK(note->nullable && !note->default_val);
    CHECK(twice->generated);
  }
  lace_schema_free(s);

  /* A row of defaults: the database fills in the key and the default */
  CHECK_OK(db, lace_insert(db->client, db->conn, "it_cols", NULL, NULL, 0));
  LaceResult *r = it_q(db, "SELECT id, name, twice FROM it_cols");
  CHECK(r && r->num_rows == 1);
  char *nm = it_text(r, 0, 1);
  CHECK_STR(nm, "anon");
  free(nm);
  CHECK(r && it_int(r, 0, 0) >= 1 && it_int(r, 0, 2) == 42);
  lace_result_free(r);
  it_ex(db, "DROP TABLE it_cols");
}

/* Composite keys are reported column by column */
static void test_composite_key(ItDb *db) {
  it_ex(db, "DROP TABLE IF EXISTS it_ck");
  it_ex(db, "CREATE TABLE it_ck (a INTEGER NOT NULL, b VARCHAR(10) NOT NULL, "
            "v INTEGER, PRIMARY KEY (a, b))");
  LaceSchema *s = NULL;
  CHECK_OK(db, lace_get_schema(db->client, db->conn, "it_ck", &s));
  const LaceColumn *a = find_col(s, "a"), *b = find_col(s, "b"), *v = find_col(s, "v");
  CHECK(a && b && v && a->primary_key && b->primary_key && !v->primary_key);
  lace_schema_free(s);
  it_ex(db, "DROP TABLE it_ck");
}

/* Odd names: listed, quoted and read through their reference */
static void test_odd_names(ItDb *db) {
  const char *create = it_dialect(db, "CREATE TABLE \"it odd\"\"name\" (id INTEGER PRIMARY KEY)",
                                  "CREATE TABLE \"it odd\"\"name\" (id INTEGER PRIMARY KEY)",
                                  "CREATE TABLE `it odd\"name` (id INT PRIMARY KEY)");
  it_ex(db, "%s", it_dialect(db, "DROP TABLE IF EXISTS \"it odd\"\"name\"",
                             "DROP TABLE IF EXISTS \"it odd\"\"name\"",
                             "DROP TABLE IF EXISTS `it odd\"name`"));
  if (!it_ex(db, "%s", create))
    return;
  /* A PostgreSQL reference quotes a part holding '"' */
  const char *ref = db->driver == LACE_DRIVER_POSTGRES ? "\"it odd\"\"name\"" : "it odd\"name";
  CHECK(listed(db, ref));
  char *q = lace_quote_table(db->driver, ref);
  CHECK(it_ex(db, "INSERT INTO %s VALUES (1)", q));
  size_t n = 0;
  CHECK_OK(db, lace_count(db->client, db->conn, ref, &n, NULL));
  CHECK_SIZE(n, 1);
  it_ex(db, "DROP TABLE %s", q);
  free(q);
}

/* PostgreSQL: tables outside the search_path are listed schema-qualified,
 * also with a '.' in a name; case is kept */
static void test_pg_schemas(ItDb *db) {
  it_ex(db, "DROP SCHEMA IF EXISTS \"ItSales\" CASCADE");
  it_ex(db, "CREATE SCHEMA \"ItSales\"");
  it_ex(db, "CREATE TABLE \"ItSales\".\"odd.name\" (id INTEGER PRIMARY KEY, v TEXT)");
  it_ex(db, "CREATE TABLE \"ItSales\".Orders (id INTEGER PRIMARY KEY)");
  CHECK(listed(db, "ItSales.\"odd.name\""));
  CHECK(listed(db, "ItSales.orders")); /* Unquoted Orders folded by the server */

  LaceSchema *s = NULL;
  CHECK_OK(db, lace_get_schema(db->client, db->conn, "ItSales.\"odd.name\"", &s));
  CHECK(s && s->num_columns == 2 && find_col(s, "id") && find_col(s, "id")->primary_key);
  lace_schema_free(s);

  const char *cols[] = {"id", "v"};
  LaceValue vals[] = {lace_value_int(1), lace_value_text("x")};
  CHECK_OK(db, lace_insert(db->client, db->conn, "ItSales.\"odd.name\"", cols, vals, 2));
  lace_value_free(&vals[1]);
  LaceResult *r = NULL;
  CHECK_OK(db, lace_query(db->client, db->conn, "ItSales.\"odd.name\"", 0, 10, &r));
  CHECK(r && r->num_rows == 1);
  lace_result_free(r);
  it_ex(db, "DROP SCHEMA \"ItSales\" CASCADE");
}

/* lace_table_dependents: the tables that reference one, with their ON
 * DELETE rules (what a delete takes with it) */
static void test_dependents(ItDb *db) {
  it_ex(db, "DROP TABLE IF EXISTS it_dep_child");
  it_ex(db, "DROP TABLE IF EXISTS it_dep_child2");
  it_ex(db, "DROP TABLE IF EXISTS it_dep_leaf");
  it_ex(db, "DROP TABLE IF EXISTS it_dep_parent");
  if (!it_ex(db, "CREATE TABLE it_dep_parent (id INTEGER PRIMARY KEY)") ||
      !it_ex(db, "CREATE TABLE it_dep_child (id INTEGER PRIMARY KEY, p INTEGER, "
                 "FOREIGN KEY (p) REFERENCES it_dep_parent(id) ON DELETE CASCADE)") ||
      !it_ex(db, "CREATE TABLE it_dep_child2 (id INTEGER PRIMARY KEY, p INTEGER, "
                 "FOREIGN KEY (p) REFERENCES it_dep_parent(id) ON DELETE SET NULL)") ||
      !it_ex(db, "CREATE TABLE it_dep_leaf (id INTEGER PRIMARY KEY)"))
    return;
  LaceDependent *deps = NULL;
  size_t n = 0;
  CHECK_OK(db, lace_table_dependents(db->client, db->conn, "it_dep_parent", &deps, &n));
  CHECK(n == 2);
  const char *cascade = NULL, *setnull = NULL;
  for (size_t i = 0; i < n; i++) {
    if (strstr(deps[i].table, "it_dep_child2")) setnull = deps[i].on_delete;
    else if (strstr(deps[i].table, "it_dep_child")) cascade = deps[i].on_delete;
  }
  CHECK_STR(cascade, "CASCADE");
  CHECK_STR(setnull, "SET NULL");
  lace_dependents_free(deps, n);
  /* A table nothing references */
  CHECK_OK(db, lace_table_dependents(db->client, db->conn, "it_dep_leaf", &deps, &n));
  CHECK(n == 0 && deps == NULL);
  it_ex(db, "DROP TABLE it_dep_child");
  it_ex(db, "DROP TABLE it_dep_child2");
  it_ex(db, "DROP TABLE it_dep_leaf");
  it_ex(db, "DROP TABLE it_dep_parent");
}

const ItTest it_schema_tests[] = {
    {"schema_columns", test_schema_columns, IT_ALL, false},
    {"composite_key", test_composite_key, IT_ALL, false},
    {"odd_names", test_odd_names, IT_ALL, false},
    {"pg_schemas", test_pg_schemas, IT_POSTGRES | IT_TUNNEL, false},
    {"dependents", test_dependents, IT_ALL, false},
    {NULL, NULL, 0, false},
};
