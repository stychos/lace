static const LaceIndex *find_index(const LaceSchema *s, LaceIndexKind kind, const char *col) {
  for (size_t i = 0; s && i < s->num_indexes; i++) {
    const LaceIndex *ix = &s->indexes[i];
    if (ix->kind != kind) continue;
    if (!col) return ix;
    for (size_t k = 0; k < ix->num_columns; k++)
      if (ix->columns[k] && strcasecmp(ix->columns[k], col) == 0) return ix;
  }
  return NULL;
}

static const LaceColumn *col_of(const LaceSchema *s, const char *name) {
  for (size_t i = 0; s && i < s->num_columns; i++)
    if (s->columns[i].name && strcmp(s->columns[i].name, name) == 0) return &s->columns[i];
  return NULL;
}

static void make_tables(ItDb *db) {
  it_ex(db, "DROP TABLE IF EXISTS it_cat_child");
  it_ex(db, "DROP TABLE IF EXISTS it_cat");
  it_ex(db, "%s",
        it_dialect(db,
                   "CREATE TABLE it_cat (id INTEGER PRIMARY KEY AUTOINCREMENT, "
                   "code TEXT COLLATE NOCASE, v INTEGER, CONSTRAINT it_pos CHECK (v > 0))",
                   "CREATE TABLE it_cat (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                   "code text COLLATE \"C\", v integer, CONSTRAINT it_pos CHECK (v > 0))",
                   "CREATE TABLE it_cat (id BIGINT AUTO_INCREMENT PRIMARY KEY, "
                   "code VARCHAR(20) COLLATE utf8mb4_bin COMMENT 'the code', v INT, "
                   "CONSTRAINT it_pos CHECK (v > 0))"));
  it_ex(db, "CREATE UNIQUE INDEX it_cat_code ON it_cat (code)");
  it_ex(db, "%s",
        it_dialect(db,
                   "CREATE TABLE it_cat_child (id INTEGER PRIMARY KEY, cat_id INTEGER, "
                   "CONSTRAINT it_child_cat FOREIGN KEY (cat_id) REFERENCES it_cat (id) ON DELETE CASCADE)",
                   "CREATE TABLE it_cat_child (id integer PRIMARY KEY, cat_id bigint, "
                   "CONSTRAINT it_child_cat FOREIGN KEY (cat_id) REFERENCES it_cat (id) ON DELETE CASCADE)",
                   "CREATE TABLE it_cat_child (id INT PRIMARY KEY, cat_id BIGINT, "
                   "CONSTRAINT it_child_cat FOREIGN KEY (cat_id) REFERENCES it_cat (id) ON DELETE CASCADE)"));
}

static void drop_tables(ItDb *db) {
  it_ex(db, "DROP TABLE IF EXISTS it_cat_child");
  it_ex(db, "DROP TABLE IF EXISTS it_cat");
}

/* Indexes, constraints, foreign keys and the column extras of lace_get_schema */
static void test_schema_extras(ItDb *db) {
  make_tables(db);
  LaceSchema *s = NULL;
  CHECK_OK(db, lace_get_schema(db->client, db->conn, "it_cat", &s));
  if (s) {
    const LaceColumn *id = col_of(s, "id"), *code = col_of(s, "code");
    CHECK(id && id->key_position == 1);
    CHECK(id && (id->auto_increment || id->identity));
    CHECK(code && code->collation != NULL);
    if (code && code->collation)
      CHECK(strcasecmp(code->collation, it_dialect(db, "NOCASE", "C", "utf8mb4_bin")) == 0);
    if (db->driver == LACE_DRIVER_MYSQL || db->driver == LACE_DRIVER_MARIADB)
      CHECK(code && code->comment && strcmp(code->comment, "the code") == 0);
    const LaceIndex *pk = find_index(s, LACE_INDEX_PRIMARY, "id");
    CHECK(pk != NULL);
    const LaceIndex *u = find_index(s, LACE_INDEX_UNIQUE, "code");
    CHECK(u != NULL && u->unique && u->name && strcmp(u->name, "it_cat_code") == 0);
    const LaceIndex *chk = find_index(s, LACE_INDEX_CHECK, NULL);
    CHECK(chk != NULL);
    if (chk) {
      CHECK(chk->check && strstr(chk->check, "v") && strstr(chk->check, "0"));
      CHECK(chk->name && strcmp(chk->name, "it_pos") == 0);
    }
    CHECK(s->num_foreign_keys == 0);
    lace_schema_free(s);
  }
  s = NULL;
  CHECK_OK(db, lace_get_schema(db->client, db->conn, "it_cat_child", &s));
  if (s) {
    CHECK(s->num_foreign_keys == 1);
    if (s->num_foreign_keys == 1) {
      const LaceForeignKey *fk = &s->foreign_keys[0];
      CHECK(fk->num_columns == 1 && fk->columns[0] && strcmp(fk->columns[0], "cat_id") == 0);
      CHECK(fk->num_ref_columns == 1 && fk->ref_columns[0] && strcmp(fk->ref_columns[0], "id") == 0);
      CHECK(fk->ref_table && strcasecmp(fk->ref_table, "it_cat") == 0);
      CHECK(fk->on_delete && strcasecmp(fk->on_delete, "CASCADE") == 0);
      if (db->driver != LACE_DRIVER_SQLITE) CHECK(fk->name && strcmp(fk->name, "it_child_cat") == 0);
    }
    lace_schema_free(s);
  }
  /* the other side */
  LaceDependent *deps = NULL;
  size_t nd = 0;
  CHECK_OK(db, lace_table_dependents(db->client, db->conn, "it_cat", &deps, &nd));
  CHECK(nd == 1);
  if (nd == 1) {
    CHECK(deps[0].num_columns == 1 && strcmp(deps[0].columns[0], "cat_id") == 0 &&
          strcmp(deps[0].ref_columns[0], "id") == 0);
    CHECK(strcmp(deps[0].on_delete, "CASCADE") == 0);
  }
  lace_dependents_free(deps, nd);
  drop_tables(db);
}

/* Views, routines and triggers, and their definitions */
static void test_objects(ItDb *db) {
  bool skip_routines = false;
  make_tables(db);
  it_ex(db, "DROP VIEW IF EXISTS it_cat_view");
  it_ex(db, "CREATE VIEW it_cat_view AS SELECT id, code FROM it_cat");
  if (db->driver == LACE_DRIVER_POSTGRES) {
    it_ex(db, "CREATE OR REPLACE FUNCTION it_cat_fn() RETURNS integer LANGUAGE sql AS 'SELECT 1'");
    it_ex(db, "CREATE OR REPLACE FUNCTION it_cat_trgfn() RETURNS trigger LANGUAGE plpgsql AS "
              "$$ BEGIN RETURN NEW; END $$");
    it_ex(db, "CREATE TRIGGER it_cat_trg BEFORE INSERT ON it_cat FOR EACH ROW EXECUTE FUNCTION it_cat_trgfn()");
  } else if (db->driver == LACE_DRIVER_SQLITE) {
    it_ex(db, "CREATE TRIGGER it_cat_trg AFTER INSERT ON it_cat BEGIN UPDATE it_cat SET v = v WHERE id = NEW.id; END");
  } else {
    /* With binary logging on, MySQL lets only SUPER create functions and
     * triggers (log_bin_trust_function_creators); without it they are skipped */
    it_ex(db, "DROP FUNCTION IF EXISTS it_cat_fn");
    if (lace_exec(db->client, db->conn, "CREATE FUNCTION it_cat_fn() RETURNS INT DETERMINISTIC RETURN 1", NULL) != LACE_OK)
      skip_routines = true;
    if (lace_exec(db->client, db->conn, "CREATE TRIGGER it_cat_trg BEFORE INSERT ON it_cat FOR EACH ROW SET NEW.v = NEW.v", NULL) != LACE_OK)
      skip_routines = true;
    if (skip_routines) fprintf(stderr, "  [%s] cannot create functions/triggers here: %s\n", db->name, lace_client_error(db->client));
  }
  LaceObject *objs = NULL;
  size_t n = 0;
  CHECK_OK(db, lace_list_objects(db->client, db->conn, &objs, &n));
  const LaceObject *view = NULL, *fn = NULL, *trg = NULL;
  for (size_t i = 0; i < n; i++) {
    if (objs[i].kind == LACE_OBJ_VIEW && objs[i].name && strcasecmp(objs[i].name, "it_cat_view") == 0) view = &objs[i];
    if (objs[i].kind == LACE_OBJ_ROUTINE && objs[i].name && strncasecmp(objs[i].name, "it_cat_fn", 9) == 0) fn = &objs[i];
    if (objs[i].kind == LACE_OBJ_TRIGGER && objs[i].name && strcasecmp(objs[i].name, "it_cat_trg") == 0) trg = &objs[i];
  }
  CHECK(view != NULL);
  if (!skip_routines) {
    CHECK(trg != NULL && trg->table && strcasecmp(trg->table, "it_cat") == 0);
    if (db->driver == LACE_DRIVER_SQLITE) CHECK(fn == NULL);
    else CHECK(fn != NULL && fn->detail && strcmp(fn->detail, "function") == 0);
  }
  char *sql = NULL;
  if (view) {
    CHECK_OK(db, lace_object_definition(db->client, db->conn, view, &sql));
    CHECK(sql && strstr(sql, "code") != NULL);
    free(sql);
    sql = NULL;
  }
  if (fn) {
    CHECK_OK(db, lace_object_definition(db->client, db->conn, fn, &sql));
    CHECK(sql && strstr(sql, "1") != NULL);
    free(sql);
    sql = NULL;
  }
  if (trg) {
    CHECK_OK(db, lace_object_definition(db->client, db->conn, trg, &sql));
    CHECK(sql && (strstr(sql, "it_cat_trg") != NULL || strstr(sql, "IT_CAT_TRG") != NULL));
    free(sql);
  }
  lace_objects_free(objs, n);
  it_ex(db, "DROP TRIGGER IF EXISTS it_cat_trg%s", db->driver == LACE_DRIVER_POSTGRES ? " ON it_cat" : "");
  it_ex(db, "DROP VIEW IF EXISTS it_cat_view");
  if (db->driver != LACE_DRIVER_SQLITE) {
    it_ex(db, "DROP FUNCTION IF EXISTS it_cat_fn");
    if (db->driver == LACE_DRIVER_POSTGRES) it_ex(db, "DROP FUNCTION IF EXISTS it_cat_trgfn");
  }
  drop_tables(db);
}

/* lace_table_info: what every driver knows about a table */
static void test_table_info(ItDb *db) {
  make_tables(db);
  it_ex(db, "INSERT INTO it_cat (code, v) VALUES ('a', 1), ('b', 2)");
  LaceTableInfo *ti = NULL;
  CHECK_OK(db, lace_table_info(db->client, db->conn, "it_cat", &ti));
  CHECK(ti != NULL);
  if (ti) {
    CHECK(ti->schema != NULL);
    CHECK(ti->total_bytes >= 0);
    if (db->driver == LACE_DRIVER_SQLITE) CHECK(ti->size_is_file || ti->data_bytes >= 0);
    if (db->driver == LACE_DRIVER_POSTGRES) CHECK(ti->owner != NULL && ti->data_bytes >= 0 && ti->index_bytes >= 0);
    if (db->driver == LACE_DRIVER_MYSQL || db->driver == LACE_DRIVER_MARIADB)
      CHECK(ti->engine != NULL && ti->collation != NULL && ti->charset != NULL);
    CHECK(!ti->partitioned);
    lace_table_info_free(ti);
  }
  drop_tables(db);
}

/* The auto-increment counter after two inserts */
static void test_autoincrement(ItDb *db) {
  make_tables(db);
  it_ex(db, "INSERT INTO it_cat (code, v) VALUES ('a', 1), ('b', 2)");
  LaceAutoInc *a = NULL;
  CHECK_OK(db, lace_autoincrement_get(db->client, db->conn, "it_cat", &a));
  CHECK(a != NULL);
  if (a) {
    CHECK(a->column && strcmp(a->column, "id") == 0);
    CHECK(a->has_counter);
    CHECK(a->max == 2);
    if (a->next != 3) it_fail(db, "next is %lld, want 3", (long long)a->next);
    if (db->driver == LACE_DRIVER_POSTGRES) CHECK(a->sequence != NULL);
    lace_autoinc_free(a);
  }
  /* a table without a counter */
  a = NULL;
  CHECK_OK(db, lace_autoincrement_get(db->client, db->conn, "it_cat_child", &a));
  CHECK(a != NULL);
  if (a) {
    if (db->driver == LACE_DRIVER_SQLITE) {
      /* INTEGER PRIMARY KEY: assigned, but no sqlite_sequence counter */
      CHECK(a->column != NULL && !a->has_counter);
    } else {
      CHECK(a->column == NULL);
    }
    lace_autoinc_free(a);
  }
  drop_tables(db);
}

